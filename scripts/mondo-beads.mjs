#!/usr/bin/env node
// Builds src/components/mondo/stage/beads.ts: every pixel of the MONDO
// masthead words, set in Alpha Lyrae's SS05 ("displaced pixels for a feeling
// of motion"), so each one can become a chrome bead.
//
// SS05 glyphs are nothing but `pixel` components (85 × 85 units, sometimes
// stretched), so the beads come straight from the font's UFO source rather
// than from rasterizing. Spacing and kerning come from HarfBuzz.
//
//   brew install harfbuzz
//   node scripts/mondo-beads.mjs
//
// Add a word to WORDS when MONDO gets a new masthead.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const WORDS = ["ERIK’S", "WEBPAGE", "PROJECTS", "TALKS"];

// Glyphs without an SS05 drawing borrow a pixel one from a sibling set.
const FALLBACK = { quoteright: "quoteright.ss01" };

const REPO = "https://raw.githubusercontent.com/vegaprotocol/alpha-lyrae/master";
const UFO = `${REPO}/src/Alpha%20Lyrae-Medium.ufo`;
const PIXEL = 85;
/** The font's pixel building blocks and their edge length in font units. */
const BLOCKS = { pixel: PIXEL, "pixel.small": PIXEL / 2 };

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cache = join(root, "node_modules/.cache/alpha-lyrae");
mkdirSync(cache, { recursive: true });

async function cached(name, url) {
  const file = join(cache, name);
  if (!existsSync(file)) {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${res.status} ${url}`);
    writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  }
  return file;
}

const font = await cached("AlphaLyrae-Medium.otf", `${REPO}/AlphaLyrae-Medium.otf`);
const contents = readFileSync(
  await cached("contents.plist", `${UFO}/glyphs/contents.plist`),
  "utf8",
);
const files = Object.fromEntries(
  [...contents.matchAll(/<key>([^<]+)<\/key>\s*<string>([^<]+)<\/string>/g)].map(
    (m) => [m[1], m[2]],
  ),
);

const num = (tag, attr, fallback) => {
  const m = tag.match(new RegExp(`\\b${attr}="([^"]+)"`));
  return m ? Number(m[1]) : fallback;
};

/** Every pixel in a glyph as [cx, cy, sx, sy]: center in font units, size in pixels. */
async function pixels(name) {
  const file = files[name];
  if (!file) throw new Error(`no glyph ${name}`);
  const xml = readFileSync(await cached(file, `${UFO}/glyphs/${file}`), "utf8");
  if (/<contour>/.test(xml)) {
    throw new Error(`${name} is drawn, not built from pixels; add a FALLBACK`);
  }

  const out = [];
  for (const [tag] of xml.matchAll(/<component\b[^>]*>/g)) {
    const base = tag.match(/base="([^"]+)"/)[1];
    const x = num(tag, "xOffset", 0);
    const y = num(tag, "yOffset", 0);
    const sx = num(tag, "xScale", 1);
    const sy = num(tag, "yScale", 1);
    const block = BLOCKS[base];
    if (block) {
      const k = block / PIXEL;
      out.push([x + (block / 2) * sx, y + (block / 2) * sy, k * sx, k * sy]);
    } else {
      for (const [cx, cy, psx, psy] of await pixels(base)) {
        out.push([x + cx * sx, y + cy * sy, psx * sx, psy * sy]);
      }
    }
  }
  return out;
}

const round = (n) => Math.round(n * 10) / 10;

const words = {};
for (const word of WORDS) {
  const shaped = JSON.parse(
    execFileSync("hb-shape", [
      "--output-format=json",
      "--features=ss05",
      font,
      word,
    ]).toString(),
  );

  const beads = [];
  let pen = 0;
  for (const [letter, { g, ax, dx, dy }] of shaped.entries()) {
    for (const [cx, cy, sx, sy] of await pixels(FALLBACK[g] ?? g)) {
      // Mirrored components (W is drawn with yScale -1) still make round beads.
      beads.push(round(pen + dx + cx), round(dy + cy), round(Math.abs(sx)), round(Math.abs(sy)), letter);
    }
    pen += ax;
  }
  words[word] = { width: pen, beads };
}

const space = JSON.parse(
  execFileSync("hb-shape", ["--output-format=json", font, " "]).toString(),
)[0].ax;

const body = Object.entries(words)
  .map(
    ([word, { width, beads }]) =>
      `  ${JSON.stringify(word)}: {\n    width: ${width},\n    beads: [${beads.join(", ")}],\n  },`,
  )
  .join("\n");

writeFileSync(
  join(root, "src/components/mondo/stage/beads.ts"),
  `// Generated by scripts/mondo-beads.mjs from Alpha Lyrae SS05. Don't edit.

/** Font units: 1000 per em, y up from the baseline. */
export const UNITS_PER_EM = 1000;
export const CAP_HEIGHT = 706;
export const SPACE = ${space};
/** One font pixel, the size a bead is drawn at when its scale is 1. */
export const PIXEL = ${PIXEL};

export type BeadWord = {
  width: number;
  /** Flat [x, y, scaleX, scaleY, letter] per bead: the pixel's center, its stretch, and which letter it's in. */
  beads: readonly number[];
};

export const WORDS: Readonly<Record<string, BeadWord>> = {
${body}
};
`,
);

for (const [word, { beads }] of Object.entries(words)) {
  console.log(`${word}: ${beads.length / 5} beads`);
}
